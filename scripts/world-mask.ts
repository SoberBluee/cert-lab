/**
 * Generates apps/web/src/system/stage/worldMask.ts: which cells of a coarse lon/lat grid are land,
 * for the dot-matrix map in System Labs. Run once; the output is committed, so the app has no
 * map dependency and works offline.
 *
 * Input: land-110m.json from the world-atlas npm package (Natural Earth 1:110m land, public domain):
 *   curl -sSfLO https://registry.npmjs.org/world-atlas/-/world-atlas-2.0.2.tgz && tar -xzf world-atlas-2.0.2.tgz
 *   node --import tsx scripts/world-mask.ts package/land-110m.json > apps/web/src/system/stage/worldMask.ts
 */
import { readFileSync } from 'node:fs';

const NORTH = 76;
const SOUTH = -56;
const CELL = 3;

type Pt = [number, number];

interface Topology {
  transform: { scale: [number, number]; translate: [number, number] };
  arcs: number[][][];
  objects: { land: { geometries: { type: 'Polygon' | 'MultiPolygon'; arcs: number[][] | number[][][] }[] } };
}

const topo = JSON.parse(readFileSync(process.argv[2]!, 'utf8')) as Topology;
const { scale, translate } = topo.transform;

// Arcs are quantized and delta-encoded.
const arcs: Pt[][] = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx!;
    y += dy!;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

// A ring lists arc indexes; ~i means arc i reversed. Consecutive arcs share an end point.
const ring = (ids: number[]): Pt[] =>
  ids.flatMap((id, n) => {
    const pts = id < 0 ? [...arcs[~id]!].reverse() : arcs[id]!;
    return n === 0 ? pts : pts.slice(1);
  });

/**
 * Rings cut at the date line (Fiji, Chukotka) jump from 180° to -180°. Split them there into
 * pieces that each close along the meridian, so the inside test below stays correct.
 */
const splitAtDateLine = (r: Pt[]): Pt[][] => {
  const pieces: Pt[][] = [[r[0]!]];
  for (let i = 1; i < r.length; i++) {
    const [x0, y0] = r[i - 1]!;
    const [x1, y1] = r[i]!;
    if (Math.abs(x1 - x0) > 180) {
      const side = x0 > 0 ? 180 : -180;
      // An edge from exactly -180° to 180° (Wrangel Island) runs along the meridian itself.
      const span = x1 + 2 * side - x0;
      const y = span ? y0 + ((side - x0) / span) * (y1 - y0) : y0;
      pieces.at(-1)!.push([side, y]);
      pieces.push([[-side, y]]);
    }
    pieces.at(-1)!.push(r[i]!);
  }
  // The ring is closed, so the last piece continues into the first.
  if (pieces.length > 1) pieces[0] = [...pieces.pop()!, ...pieces[0]!.slice(1)];
  return pieces;
};

const rings: Pt[][] = topo.objects.land.geometries
  .flatMap((g) => (g.type === 'Polygon' ? (g.arcs as number[][]).map(ring) : (g.arcs as number[][][]).flatMap((p) => p.map(ring))))
  // Antarctica lies south of the map.
  .filter((r) => Math.max(...r.map((p) => p[1])) > SOUTH)
  .flatMap(splitAtDateLine);

// Even-odd across every ring, so holes (lakes, enclosed seas) come out as water.
const isLand = (lon: number, lat: number) => {
  let inside = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i]!;
      const [xj, yj] = r[j]!;
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
};

const cols = 360 / CELL;
const rows = (NORTH - SOUTH) / CELL;
const bits: number[] = [];
for (let r = 0; r < rows; r++) {
  for (let c = 0; c < cols; c++) {
    // A cell is land if enough of a 3×3 sample is, so thin coasts (Japan, Britain) still show.
    let hits = 0;
    for (let a = 0; a < 3; a++) for (let b = 0; b < 3; b++) if (isLand(-180 + (c + (b + 0.5) / 3) * CELL, NORTH - (r + (a + 0.5) / 3) * CELL)) hits++;
    bits.push(hits >= 2 ? 1 : 0);
  }
}

const bytes = Buffer.alloc(Math.ceil(bits.length / 8));
bits.forEach((b, i) => {
  if (b) bytes[i >> 3]! |= 0x80 >> (i & 7);
});

console.log(`// Generated by scripts/world-mask.ts from world-atlas 2.0.2 land-110m.json
// (Natural Earth 1:110m land, public domain). Do not edit by hand.

/** Land cells of a ${CELL}° grid from ${NORTH}°N to ${-SOUTH}°S, row by row from the north-west, one bit per cell. */
export const WORLD_MASK = {
  west: -180,
  north: ${NORTH},
  cell: ${CELL},
  cols: ${cols},
  rows: ${rows},
  bits: '${bytes.toString('base64')}',
} as const;`);

if (process.env.PREVIEW) {
  for (let r = 0; r < rows; r++) process.stderr.write(bits.slice(r * cols, (r + 1) * cols).map((b) => (b ? '#' : '.')).join('') + '\n');
}
